-- ==============================================================
-- HSE INDUCTION MODULE - DATABASE SCHEMA
-- ==============================================================

-- 1. Employee Induction Master Status Table
CREATE TABLE IF NOT EXISTS `hse_employee_induction` (
  `ID` int(11) NOT NULL AUTO_INCREMENT,
  `EMP_AUTO_ID` int(11) NOT NULL,
  `LOGIN_ID` int(11) DEFAULT NULL,
  `TYPE_ID` int(11) NOT NULL DEFAULT 2 COMMENT '1: Visitor, 2: Employee, 3: Contractor',
  `INDUCTION_STATUS` enum('NOT_STARTED','IN_PROGRESS','PASSED','FAILED') NOT NULL DEFAULT 'NOT_STARTED',
  `VIDEO_STATUS` enum('NOT_WATCHED','WATCHING','COMPLETED') NOT NULL DEFAULT 'NOT_WATCHED',
  `VIDEO_WATCHED_SECONDS` int(11) DEFAULT 0,
  `TOTAL_QUESTIONS` int(11) DEFAULT 0,
  `CORRECT_ANSWERS` int(11) DEFAULT 0,
  `WRONG_ANSWERS` int(11) DEFAULT 0,
  `SCORE_PERCENTAGE` decimal(5,2) DEFAULT 0.00,
  `ATTEMPTS` int(11) DEFAULT 0,
  `CERTIFICATE_NO` varchar(100) DEFAULT NULL,
  `QR_CODE_PATH` varchar(255) DEFAULT NULL,
  `LAST_ATTEMPT_DATE` datetime DEFAULT NULL,
  `PASSED_DATE` datetime DEFAULT NULL,
  `VALIDITY_DATE` date DEFAULT NULL,
  `STATUS` enum('Y','N') NOT NULL DEFAULT 'Y',
  `CREATED_ON` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_ON` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID`),
  KEY `EMP_AUTO_ID` (`EMP_AUTO_ID`),
  KEY `LOGIN_ID` (`LOGIN_ID`),
  KEY `TYPE_ID` (`TYPE_ID`),
  KEY `INDUCTION_STATUS` (`INDUCTION_STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

-- 2. Employee Induction Attempt Summary History Log
CREATE TABLE IF NOT EXISTS `hse_induction_attempts` (
  `ATTEMPT_ID` int(11) NOT NULL AUTO_INCREMENT,
  `INDUCTION_ID` int(11) NOT NULL,
  `EMP_AUTO_ID` int(11) NOT NULL,
  `ATTEMPT_NUMBER` int(11) NOT NULL DEFAULT 1,
  `TYPE_ID` int(11) NOT NULL DEFAULT 2,
  `TOTAL_QUESTIONS` int(11) NOT NULL DEFAULT 0,
  `QUESTIONS_ANSWERED` int(11) NOT NULL DEFAULT 0,
  `CORRECT_ANSWERS` int(11) NOT NULL DEFAULT 0,
  `INCORRECT_ANSWERS` int(11) NOT NULL DEFAULT 0,
  `TOTAL_AVAILABLE_MARKS` decimal(8,2) NOT NULL DEFAULT 100.00,
  `MARKS_OBTAINED` decimal(8,2) NOT NULL DEFAULT 0.00,
  `PERCENTAGE` decimal(5,2) NOT NULL DEFAULT 0.00,
  `PASS_FAIL_STATUS` enum('PASSED','FAILED') NOT NULL,
  `TIME_TAKEN_SECONDS` int(11) NOT NULL DEFAULT 0,
  `ATTEMPT_STARTED_AT` datetime DEFAULT NULL,
  `ATTEMPT_COMPLETED_AT` datetime NOT NULL,
  `CERTIFICATE_NO` varchar(100) DEFAULT NULL,
  `QR_CODE_PATH` varchar(255) DEFAULT NULL,
  `IP_ADDRESS` varchar(45) DEFAULT NULL,
  `CREATED_ON` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`ATTEMPT_ID`),
  KEY `INDUCTION_ID` (`INDUCTION_ID`),
  KEY `EMP_AUTO_ID` (`EMP_AUTO_ID`),
  KEY `PASS_FAIL_STATUS` (`PASS_FAIL_STATUS`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

-- 3. Individual Question-by-Question Snapshot Log (Permanent Audit Trail)
CREATE TABLE IF NOT EXISTS `hse_induction_attempt_answers` (
  `ANSWER_LOG_ID` int(11) NOT NULL AUTO_INCREMENT,
  `ATTEMPT_ID` int(11) NOT NULL,
  `EMP_AUTO_ID` int(11) NOT NULL,
  `QUESTION_ID` int(11) NOT NULL,
  `QUESTION_NUMBER` int(11) NOT NULL DEFAULT 1,
  `QUESTION_TEXT` text NOT NULL,
  `QUESTION_IMG` text DEFAULT NULL,
  `OPTION_A` text DEFAULT NULL,
  `OPTION_A_IMG` text DEFAULT NULL,
  `OPTION_B` text DEFAULT NULL,
  `OPTION_B_IMG` text DEFAULT NULL,
  `OPTION_C` text DEFAULT NULL,
  `OPTION_C_IMG` text DEFAULT NULL,
  `OPTION_D` text DEFAULT NULL,
  `OPTION_D_IMG` text DEFAULT NULL,
  `SELECTED_OPTION` varchar(10) NOT NULL,
  `SELECTED_OPTION_TEXT` text DEFAULT NULL,
  `CORRECT_OPTION` varchar(10) NOT NULL,
  `CORRECT_OPTION_TEXT` text DEFAULT NULL,
  `IS_CORRECT` tinyint(1) NOT NULL DEFAULT 0,
  `MARKS_ALLOCATED` decimal(5,2) NOT NULL DEFAULT 1.00,
  `MARKS_AWARDED` decimal(5,2) NOT NULL DEFAULT 0.00,
  `CREATED_ON` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`ANSWER_LOG_ID`),
  KEY `ATTEMPT_ID` (`ATTEMPT_ID`),
  KEY `EMP_AUTO_ID` (`EMP_AUTO_ID`),
  KEY `QUESTION_ID` (`QUESTION_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;

